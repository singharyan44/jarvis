def stream_examples(examples: list, output_file: Path, chunk_size: int = 10000):
    """Stream examples to file in chunks to avoid memory issues."""
    buffer = []
    count = 0
    label_counts = {"DENY": 0, "ALLOW": 0}
    
    for ex in examples:
        buffer.append(json.dumps(ex))
        label_counts[ex["label"]] = label_counts.get(ex["label"], 0) + 1
        count += 1
        
        if len(buffer) >= chunk_size:
            with open(output_file, "a") as f:
                f.write("\n".join(buffer) + "\n")
            buffer.clear()
    
    if buffer:
        with open(output_file, "a") as f:
            f.write("\n".join(buffer) + "\n")
    
    return count, label_counts


def main():
    output_dir = Path(__file__).parent
    output_dir.mkdir(parents=True, exist_ok=True)
    output_file = output_dir / "redteam_stage3.jsonl"
    
    # Clear file
    output_file.write_text("")
    
    print(f"Generating Stage 3 red-team examples...")
    
    examples = generate_adversarial_examples()
    
    # Use streaming write
    count, labels = stream_examples(examples, output_file)
    
    # Read back and shuffle
    print("Shuffling...")
    with open(output_file, "r") as f:
        lines = f.readlines()
    random.shuffle(lines)
    with open(output_file, "w") as f:
        f.writelines(lines)
    
    print(f"Generated {count} Stage 3 red-team examples")
    for k, v in labels.items():
        print(f"  {k}: {v}")


if __name__ == "__main__":
    main()